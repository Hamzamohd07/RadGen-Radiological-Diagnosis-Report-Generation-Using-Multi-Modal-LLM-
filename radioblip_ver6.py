class QFormerPretrainer(nn.Module):
    """
    Pretrains the Q-Former using ITC + ITM + IGT losses.

    Shares vision_encoder, vision_proj, and qformer with the base
    RadBLIPBioGPT instance, so all gradient updates flow directly into
    the weights that Stage 1 will continue training — no copy needed.

    FIX 2 (IGT vocab): lm_head now projects into BioGPT's vocabulary
    (42,384 tokens) instead of BERT's (30,522 tokens), and the IGT text
    is encoded with BioGPT's tokenizer.  This makes the IGT language
    supervision directly compatible with Stage 1 generation targets.

    FIX 3 (silent mask drop): _run_qformer now passes visual_att_mask as
    encoder_attention_mask so padding in the visual token sequence is
    masked correctly inside the Q-Former cross-attention layers.
    """
    def __init__(self, base_model: RadBLIPBioGPT):
        super().__init__()

        # Shared weights with RadBLIPBioGPT — updates here persist to Stage 1
        self.vision_encoder   = base_model.vision_encoder
        self.vision_proj      = base_model.vision_proj
        self.qformer          = base_model.qformer
        self.num_query_tokens = base_model.num_query_tokens
        qformer_dim           = self.qformer.config.hidden_size   # 768

        # BERT — for ITC / ITM text encoding only
        self.bert_tokenizer = BertTokenizer.from_pretrained("bert-base-uncased")
        self.bert_tokenizer.add_special_tokens({"bos_token": "[DEC]"})
        self.dec_token_id_bert = self.bert_tokenizer.convert_tokens_to_ids("[DEC]")

        self.bert = BertModel.from_pretrained("bert-base-uncased")
        self.bert.resize_token_embeddings(len(self.bert_tokenizer))
        for p in self.bert.parameters():
            p.requires_grad = False
        for layer in list(self.bert.encoder.layer)[-4:]:
            for p in layer.parameters():
                p.requires_grad = True

        bert_dim = self.bert.config.hidden_size   # 768
 
        self.biogpt_tokenizer = AutoTokenizer.from_pretrained("microsoft/biogpt")
        biogpt_vocab_size     = base_model.llm.config.vocab_size   # 42,384
        # Reuse BioGPT's input embedding layer (frozen) to encode IGT text
        self.biogpt_embed = base_model.llm.get_input_embeddings()
        for p in self.biogpt_embed.parameters():
            p.requires_grad = False
        biogpt_embed_dim = base_model.llm.config.hidden_size       # 1024

        # Project Q-Former dim (768) → BioGPT embed dim (1024) for IGT encoding
        self.igt_proj = nn.Linear(qformer_dim, biogpt_embed_dim)

        # ITC / ITM projections
        self.vision_projection = nn.Linear(qformer_dim, qformer_dim)
        self.text_projection   = nn.Linear(bert_dim,    qformer_dim)
        self.temperature       = nn.Parameter(torch.ones([]) * 0.07)
        self.itm_head          = nn.Linear(qformer_dim, 2)

        # FIX 2: lm_head over BioGPT vocab, preceded by igt_proj
        self.lm_head = nn.Linear(biogpt_embed_dim, biogpt_vocab_size)

        self._init_weights()

    def _init_weights(self):
        for lin in [self.vision_projection, self.text_projection, self.igt_proj]:
            nn.init.kaiming_normal_(lin.weight, nonlinearity="relu")
            nn.init.zeros_(lin.bias)
        for lin in [self.itm_head, self.lm_head]:
            nn.init.normal_(lin.weight, std=0.02)
            nn.init.zeros_(lin.bias)
        nn.init.constant_(self.temperature, 0.07)

    def _encode_images(self, images, image_mask):
        B, N, C, H, W = images.shape
   
        chunks = []
        for b in range(B):
            chunk = self.vision_encoder(images[b])   # [N, H, W] → [N, 257, 768]
            chunk = self.vision_proj(chunk)
            chunks.append(chunk)
        image_embeds = torch.stack(chunks, dim=0)    # [B, N, 257, 768]
        torch.cuda.empty_cache()
        T, D = image_embeds.shape[2], image_embeds.shape[3]
        image_embeds = image_embeds.view(B, N, T, D)

        fused_tokens, visual_att_masks = [], []
        for i in range(B):
            valid = image_embeds[i][image_mask[i].bool()]
            fused_tokens.append(valid.reshape(-1, D))

        max_tokens = max(t.shape[0] for t in fused_tokens)
        padded_visuals, visual_att_mask = [], []
        for t in fused_tokens:
            pad_len = max_tokens - t.shape[0]
            padded  = torch.cat([t, torch.zeros(pad_len, D, device=t.device, dtype=t.dtype)], dim=0)
            mask    = torch.cat([torch.ones(t.shape[0], device=t.device),
                                 torch.zeros(pad_len, device=t.device)])
            padded_visuals.append(padded)
            visual_att_mask.append(mask)

        image_feats = torch.stack(padded_visuals)
        image_feats = F.normalize(image_feats, dim=-1)
        return image_feats, torch.stack(visual_att_mask)   # [B,T,D], [B,T]

    def _encode_text_bert(self, text_input_ids, text_attn_mask):
        return self.bert(
            input_ids=text_input_ids,
            attention_mask=text_attn_mask,
            return_dict=True,
        )

    def _run_qformer(self, image_feats, visual_att_mask, queries):
      
        q_out = self.qformer(
            query_embeds=queries,
            encoder_hidden_states=image_feats,
            encoder_attention_mask=visual_att_mask,   # FIX 3
            return_dict=True,
        )
        return q_out.last_hidden_state   # [B, Q, 768]

    def forward(self, images, image_mask, text_input_ids, text_attn_mask,
                igt_input_ids, igt_attn_mask, igt_labels):
        """
        images          : [B, N, 3, 224, 224]
        image_mask      : [B, N]
        text_input_ids  : [B, L]   BERT tokens for ITC/ITM
        text_attn_mask  : [B, L]
        igt_input_ids   : [B, L2]  BioGPT tokens for IGT
        igt_attn_mask   : [B, L2]
        igt_labels      : [B, L2]  BioGPT token ids, -100 on padding/prefix
        """
        B      = images.shape[0]
        device = images.device

        image_feats, visual_att_mask = self._encode_images(images, image_mask)

        text_output = self._encode_text_bert(text_input_ids, text_attn_mask)
        text_embeds = text_output.last_hidden_state    # [B, L, 768]

        queries = self.qformer.query_tokens.expand(B, -1, -1).clone()
        Q       = queries.shape[1]

        # ── ITC ───────────────────────────────────────────────
        updated_queries_itc = self._run_qformer(image_feats, visual_att_mask, queries)

        queries_itc = F.normalize(self.vision_projection(updated_queries_itc), dim=-1)
        cls_text    = F.normalize(self.text_projection(text_embeds[:, 0, :]),   dim=-1)

        sim_i2t = torch.einsum("bqd, td -> btq", queries_itc, cls_text)
        sim_i2t, _ = sim_i2t.max(dim=-1)
        sim_i2t = sim_i2t / self.temperature
        sim_t2i = sim_i2t.T

        targets  = torch.arange(B, device=device)
        loss_itc = (
            F.cross_entropy(sim_i2t, targets, label_smoothing=0.1) +
            F.cross_entropy(sim_t2i, targets, label_smoothing=0.1)
        ) / 2

        # ── ITM ───────────────────────────────────────────────
        with torch.no_grad():
            sim_i2t_neg = sim_i2t.clone().fill_diagonal_(-10000)
            sim_t2i_neg = sim_t2i.clone().fill_diagonal_(-10000)
            weights_i2t = torch.softmax(sim_i2t_neg, dim=-1)
            weights_t2i = torch.softmax(sim_t2i_neg, dim=-1)

        image_feats_neg = torch.stack([
            image_feats[torch.multinomial(weights_t2i[b], 1).item()] for b in range(B)
        ])
        vis_mask_neg = torch.stack([
            visual_att_mask[torch.multinomial(weights_t2i[b], 1).item()] for b in range(B)
        ])
        text_embeds_neg = torch.stack([
            text_embeds[torch.multinomial(weights_i2t[b], 1).item()] for b in range(B)
        ])

        # 3× batch: [pos, neg-img, neg-txt]
        # Chunked into 3 separate B-sized Q-Former passes to avoid the
        # 3*B×257-token cross-attention OOM that kills Rad-DINO training.
        queries_single    = self.qformer.query_tokens.expand(B, -1, -1).clone()
        q_pos             = self._run_qformer(image_feats,     visual_att_mask, queries_single)
        q_neg_img         = self._run_qformer(image_feats_neg, vis_mask_neg,    queries_single)
        q_neg_txt         = self._run_qformer(image_feats,     visual_att_mask, queries_single)
        updated_queries_itm = torch.cat([q_pos, q_neg_img, q_neg_txt], dim=0)  # [3*B, Q, D]
        torch.cuda.empty_cache()

        itm_logits = self.itm_head(updated_queries_itm).mean(dim=1)
        itm_labels = torch.cat([
            torch.ones(B,  dtype=torch.long, device=device),   # pos
            torch.zeros(B, dtype=torch.long, device=device),   # neg-img
            torch.ones(B,  dtype=torch.long, device=device),   # neg-txt → 1 (image correct)
        ])
        loss_itm = F.cross_entropy(itm_logits, itm_labels)

        # ── IGT ── BioGPT vocab ───────────────────────────────
        # FIX 2: embed IGT tokens with BioGPT's embedding, project Q-Former
        # output to BioGPT's embed dim, then apply lm_head over BioGPT vocab.
        queries_igt = self.qformer.query_tokens.expand(B, -1, -1).clone()
        updated_queries_igt = self._run_qformer(image_feats, visual_att_mask, queries_igt)
        # [B, Q, 768] → [B, Q, 1024]
        projected_queries = self.igt_proj(updated_queries_igt)

        # BioGPT token embeddings for IGT text
        biogpt_embeds = self.biogpt_embed(igt_input_ids)   # [B, L2, 1024]

        # Concatenate visual query embeddings before text embeddings (image-grounded)
        igt_input_embeds = torch.cat([projected_queries, biogpt_embeds], dim=1)  # [B, Q+L2, 1024]

        # Only compute logits over the text portion
        text_logits    = self.lm_head(igt_input_embeds[:, Q:, :])   # [B, L2, vocab]
        shifted_logits = text_logits[:, :-1, :]                      # [B, L2-1, vocab]
        shifted_labels = igt_labels[:, 1:]                           # [B, L2-1]

        loss_igt = F.cross_entropy(
            shifted_logits.reshape(-1, shifted_logits.shape[-1]),
            shifted_labels.reshape(-1),
            ignore_index=-100,
        )

        total_loss = loss_itc + loss_itm + loss_igt
        return total_loss, {"itc": loss_itc.item(), "itm": loss_itm.item(), "igt": loss_igt.item()}

# ── 8d.  PRETRAINING LOOP ────────────────────────────────────

def _prepare_igt_batch(biogpt_tokenizer, reports, max_length, device):
    """
    Tokenize short reports with BioGPT tokenizer for IGT supervision.
    Returns input_ids, attention_mask, and labels (prompt tokens masked).
    Called inside pretrain_qformer per batch.
    """
    enc = biogpt_tokenizer(
        reports,
        padding="max_length",
        truncation=True,
        max_length=max_length,
        return_tensors="pt",
    )
    input_ids      = enc["input_ids"].to(device)
    attention_mask = enc["attention_mask"].to(device)
    labels         = input_ids.clone()
    labels[attention_mask == 0] = -100   # mask padding
    return input_ids, attention_mask, labels


def pretrain_qformer(
    pretrain_model,
    loader,
    optimizer,
    epochs,
    device,
    max_grad_norm      = 1.0,
    warmup_ratio       = 0.1,
    save_dir           = "checkpoints",
    early_stopper      = None,
    accumulation_steps = 1,
    igt_max_length     = 128,
    resume_ckpt        = None,
):
 
    from transformers import get_cosine_schedule_with_warmup

    # Support optional validation loader
    if isinstance(loader, (tuple, list)):
        train_loader, val_loader = loader
    else:
        train_loader, val_loader = loader, None

    os.makedirs(save_dir, exist_ok=True)
    scaler = torch.amp.GradScaler("cuda", init_scale=1024)

    total_steps  = (len(train_loader) // accumulation_steps) * epochs
    warmup_steps = max(1, int(total_steps * warmup_ratio))
    scheduler    = get_cosine_schedule_with_warmup(
        optimizer, num_warmup_steps=warmup_steps, num_training_steps=total_steps
    )

    biogpt_tok  = pretrain_model.biogpt_tokenizer
    best_loss   = float("inf")
    start_epoch = 1

    if resume_ckpt is not None and os.path.exists(resume_ckpt):
        ckpt = torch.load(resume_ckpt, map_location="cpu")
        pretrain_model.qformer.load_state_dict(ckpt["qformer"])
        pretrain_model.vision_proj.load_state_dict(ckpt["vision_proj"])
        pretrain_model.igt_proj.load_state_dict(ckpt["igt_proj"])
        optimizer.load_state_dict(ckpt["optimizer"])
        scheduler.load_state_dict(ckpt["scheduler"])
        best_loss   = ckpt["loss"]
        start_epoch = ckpt["epoch"] + 1
        print(f"[pretrain] Resumed from epoch {ckpt['epoch']}  best_loss={best_loss:.4f}")
        print(f"[pretrain] Continuing from epoch {start_epoch} → {epochs}")

    for epoch in range(start_epoch, epochs + 1):
        pretrain_model.train()
        epoch_loss = epoch_itc = epoch_itm = epoch_igt = 0.0
        num_batches = 0

        loop = tqdm(train_loader, desc=f"[pretrain] Epoch {epoch}/{epochs}", leave=False)
        optimizer.zero_grad()

        for i, batch in enumerate(loop):
            images         = batch["images"].to(device)
            image_mask     = batch["image_mask"].to(device)
            text_input_ids = batch["text_input_ids"].to(device)
            text_attn_mask = batch["text_attn_mask"].to(device)

            # FIX 2: decode BERT tokens back to strings, re-tokenize with BioGPT
            raw_texts = pretrain_model.bert_tokenizer.batch_decode(
                text_input_ids, skip_special_tokens=True
            )
            igt_ids, igt_mask, igt_labels = _prepare_igt_batch(
                biogpt_tok, raw_texts, igt_max_length, device
            )

            with torch.amp.autocast("cuda"):
                total_loss, loss_dict = pretrain_model(
                    images, image_mask,
                    text_input_ids, text_attn_mask,
                    igt_ids, igt_mask, igt_labels,
                )
                total_loss = total_loss / accumulation_steps

            scaler.scale(total_loss).backward()

            if (i + 1) % accumulation_steps == 0:
                scaler.unscale_(optimizer)
                nn.utils.clip_grad_norm_(
                    filter(lambda p: p.requires_grad, pretrain_model.parameters()),
                    max_grad_norm,
                )
                scaler.step(optimizer)
                scaler.update()
                optimizer.zero_grad()
                scheduler.step()

                epoch_loss  += total_loss.item() * accumulation_steps
                epoch_itc   += loss_dict["itc"]
                epoch_itm   += loss_dict["itm"]
                epoch_igt   += loss_dict["igt"]
                num_batches += 1

                loop.set_postfix(
                    total=f"{total_loss.item() * accumulation_steps:.4f}",
                    itc=f"{loss_dict['itc']:.4f}",
                    itm=f"{loss_dict['itm']:.4f}",
                    igt=f"{loss_dict['igt']:.4f}",
                    lr=f"{scheduler.get_last_lr()[0]:.2e}",
                )

        mean_train_loss = epoch_loss / max(num_batches, 1)

        # ── Validation pass ───────────────────────────
        if val_loader is not None:
            pretrain_model.eval()
            val_loss_sum, val_n = 0.0, 0
            with torch.no_grad():
                for vbatch in val_loader:
                    vimages     = vbatch["images"].to(device)
                    vimg_mask   = vbatch["image_mask"].to(device)
                    vtxt_ids    = vbatch["text_input_ids"].to(device)
                    vtxt_mask   = vbatch["text_attn_mask"].to(device)
                    vraw        = pretrain_model.bert_tokenizer.batch_decode(
                        vtxt_ids, skip_special_tokens=True
                    )
                    vigt_ids, vigt_mask, vigt_labels = _prepare_igt_batch(
                        biogpt_tok, vraw, igt_max_length, device
                    )
                    with torch.amp.autocast("cuda"):
                        vloss, _ = pretrain_model(
                            vimages, vimg_mask, vtxt_ids, vtxt_mask,
                            vigt_ids, vigt_mask, vigt_labels,
                        )
                    val_loss_sum += vloss.item()
                    val_n        += 1
            mean_val_loss = val_loss_sum / max(val_n, 1)
            stop_loss = mean_val_loss
        else:
            mean_val_loss = None
            stop_loss     = mean_train_loss

        val_str = f"  val={mean_val_loss:.4f}" if mean_val_loss is not None else ""
        tqdm.write(
            f"[pretrain] Epoch {epoch}/{epochs}  "
            f"train={mean_train_loss:.4f}{val_str}  "
            f"ITC={epoch_itc/max(num_batches,1):.4f}  "
            f"ITM={epoch_itm/max(num_batches,1):.4f}  "
            f"IGT={epoch_igt/max(num_batches,1):.4f}  "
            f"lr={scheduler.get_last_lr()[0]:.2e}"
        )

        if stop_loss < best_loss:
            best_loss = stop_loss
            ckpt_path = os.path.join(save_dir, "qformer_pretrain_best.pt")
            torch.save({
                "epoch":       epoch,
                "loss":        best_loss,
                "itc":         epoch_itc / max(num_batches, 1),
                "itm":         epoch_itm / max(num_batches, 1),
                "igt":         epoch_igt / max(num_batches, 1),
                "qformer":     pretrain_model.qformer.state_dict(),
                "vision_proj": pretrain_model.vision_proj.state_dict(),
                "igt_proj":    pretrain_model.igt_proj.state_dict(),   # saved to init model.proj at Stage 1
                "optimizer":   optimizer.state_dict(),
                "scheduler":   scheduler.state_dict(),
            }, ckpt_path)
            tqdm.write(f"  ↳ Best ({best_loss:.4f}) → {ckpt_path}")

        if epoch % 2 == 0:
            torch.save(
                pretrain_model.qformer.state_dict(),
                os.path.join(save_dir, f"qformer_pretrain_epoch{epoch}.pt")
            )

        if early_stopper is not None and early_stopper.step(stop_loss):
            tqdm.write(f"[pretrain] Early stopping at epoch {epoch}.")
            break

    return pretrain_model


def load_pretrained_qformer(base_model: RadBLIPBioGPT, ckpt_path: str):
    """
    Load Stage 0 weights into RadBLIPBioGPT.

    Loads:
      qformer     → base_model.qformer
      vision_proj → base_model.vision_proj
      igt_proj    → base_model.proj   (same shape: 768 → 1024)

    igt_proj was trained during Stage 0 IGT to map Q-Former output into
    BioGPT's embedding space.  base_model.proj has the identical dimensions
    (qformer.config.hidden_size=768 → llm.config.hidden_size=1024), so the
    weights transfer directly.  This means Stage 1 starts with a proj layer
    that already knows how to bridge Q-Former → BioGPT, rather than learning
    it from scratch.
    """
    ckpt = torch.load(ckpt_path, map_location="cpu")
    base_model.qformer.load_state_dict(ckpt["qformer"])
    base_model.vision_proj.load_state_dict(ckpt["vision_proj"])
    base_model.proj.load_state_dict(ckpt["igt_proj"])   # transfer igt_proj → model.proj
    print(f"[LoadQFormer] Loaded pretrained Q-Former + igt_proj from {ckpt_path}")
    print(f"  loss={ckpt['loss']:.4f}  ITC={ckpt['itc']:.4f}  "
          f"ITM={ckpt['itm']:.4f}  IGT={ckpt['igt']:.4f}")
    print(f"  igt_proj → model.proj  (768 → 1024, warm-started)")
    return base_model, ckpt

