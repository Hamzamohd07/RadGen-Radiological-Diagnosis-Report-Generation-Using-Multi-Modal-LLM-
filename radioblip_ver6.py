class EarlyStopping:
    def __init__(self, patience: int = 3, min_delta: float = 1e-4):
        self.patience  = patience
        self.min_delta = min_delta
        self.best_loss = float("inf")
        self.counter   = 0

    def step(self, val_loss: float) -> bool:
        """Returns True if training should stop."""
        if val_loss < self.best_loss - self.min_delta:
            self.best_loss = val_loss
            self.counter   = 0
            return False
        self.counter += 1
        print(f"[EarlyStopping] No improvement for {self.counter} / {self.patience} epoch(s).")
        return self.counter >= self.patience

def train_stage(
    model: nn.Module,
    loader: DataLoader,
    optimizer: torch.optim.Optimizer,
    epochs: int,
    start_epoch: int = 1,
    scheduler_state: dict | None = None,
    device: str="cuda" if torch.cuda.is_available() else "cpu",
    stage_name: str          = "stage",
    max_grad_norm: float     = 0.5,
    warmup_ratio: float      = 0.2,
    save_dir: str            = "checkpoints",
    early_stopper: EarlyStopping | None = None,
    accumulation_steps: int  = 1,           
):
    os.makedirs(save_dir, exist_ok=True)

    scaler = torch.amp.GradScaler("cuda", init_scale=1024)

    
    total_steps  = (len(loader) // accumulation_steps) * epochs
    warmup_steps = max(1, int(total_steps * warmup_ratio))
    scheduler    = get_cosine_schedule_with_warmup(
        optimizer,
        num_warmup_steps=warmup_steps,
        num_training_steps=total_steps,
    )
    if scheduler_state is not None:
        scheduler.load_state_dict(scheduler_state)

    best_loss = float("inf")


    for epoch in range(start_epoch, epochs + 1):
        model.train()
        epoch_loss  = 0.0
        num_batches = 0

        loop = tqdm(loader, desc=f"[{stage_name}] Epoch {epoch}/{epochs}", leave=False)
        optimizer.zero_grad()                  # zero once before the epoch

        for i, batch in enumerate(loop):
            images         = batch["images"].to(device)
            image_mask     = batch["image_mask"].to(device)
            input_ids      = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            labels         = batch["labels"].to(device)

            with torch.amp.autocast("cuda"):
                loss = model(
                    images=images,
                    image_mask=image_mask,
                    input_ids=input_ids,
                    attention_mask=attention_mask,
                    labels=labels,
                )
                loss = loss / accumulation_steps   # normalize so scale stays correct

            scaler.scale(loss).backward()          # gradients accumulate here

            # Only step every `accumulation_steps` batches
            if (i + 1) % accumulation_steps == 0:
                scaler.unscale_(optimizer)
                nn.utils.clip_grad_norm_(
                    filter(lambda p: p.requires_grad, model.parameters()),
                    max_grad_norm,
                )
                scaler.step(optimizer)
                scaler.update()
                optimizer.zero_grad()               
                scheduler.step()

            loss_val     = loss.item() * accumulation_steps   # un-normalize for display
            epoch_loss  += loss_val
            num_batches += 1

            loop.set_postfix(
                loss=f"{loss_val:.4f}",
                lr=f"{scheduler.get_last_lr()[0]:.2e}",
            )

        mean_loss = epoch_loss / max(num_batches, 1)
           # After epoch ends, print one clean summary line
        tqdm.write(
            f"[{stage_name}] Epoch {epoch}/{epochs}  "
            f"mean_loss={mean_loss:.4f}  "
            f"lr={scheduler.get_last_lr()[0]:.2e}"
        )

        if mean_loss < best_loss:
            best_loss = mean_loss
            ckpt_path = os.path.join(save_dir, f"{stage_name}_best.pt")
            torch.save({
                "epoch":      epoch,
                "model":      model.state_dict(),
                "optimizer":  optimizer.state_dict(),
                "scheduler":  scheduler.state_dict(),
                "loss":       best_loss,
            }, ckpt_path)
            tqdm.write(f"  ↳ New best ({best_loss:.4f}) — checkpoint saved → {ckpt_path}")

        if epoch % 2 == 0:
            periodic_path = os.path.join(save_dir, f"{stage_name}_epoch{epoch}.pt")
            torch.save(model.state_dict(), periodic_path)

        if early_stopper is not None and early_stopper.step(mean_loss):
            print(f"[{stage_name}] Early stopping triggered at epoch {epoch}.")
            break

