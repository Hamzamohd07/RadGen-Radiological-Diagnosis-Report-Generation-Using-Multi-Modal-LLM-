# ── 8b.  ATTENTION MASK GENERATOR ────────────────────────────

def generate_attention_mask(task: str, query_len: int, pad_mask: torch.Tensor, device: str):
    """
    Generates attention mask for the CrossModalTransformer.
    Convention: 0 = can attend, -inf = cannot attend.

    task      : "itc" | "itm" | "igt"
    query_len : number of learnable query tokens Q
    pad_mask  : (B, L) — 1=valid token, 0=padding
    """
    batch_size, text_len = pad_mask.size()
    total_len = query_len + text_len

    task_mask = torch.zeros((batch_size, total_len, total_len), device=device)

    if task == "itm":
        pass  # full attention

    elif task == "igt":
        causal_indices = torch.triu_indices(text_len, text_len, offset=1, device=device)
        for b in range(batch_size):
            task_mask[b,
                      query_len + causal_indices[0],
                      query_len + causal_indices[1]] = float("-inf")
        task_mask[:, :query_len, query_len:] = float("-inf")

    elif task == "itc":
        task_mask[:, :query_len, query_len:] = float("-inf")
        task_mask[:, query_len:, :query_len] = float("-inf")

    padding_positions = (pad_mask == 0)
    for b in range(batch_size):
        if padding_positions[b].any():
            pad_idx = torch.nonzero(padding_positions[b], as_tuple=True)[0]
            task_mask[b, :, query_len + pad_idx] = float("-inf")
            task_mask[b, query_len + pad_idx, :] = float("-inf")

    return task_mask


