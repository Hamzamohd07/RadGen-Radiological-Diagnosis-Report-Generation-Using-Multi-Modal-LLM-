def load_and_expand_dataframe(csv_path: str) -> pd.DataFrame:
    """
    Reads the raw MIMIC-CXR CSV, expands each row (which contains
    lists of image paths and reports) into one row per study,
    and concatenates the augmented text onto the base report.
    """
    df = pd.read_csv(csv_path)

    # Parse stringified lists
    df["image_list"]    = df["image"].apply(ast.literal_eval)
    df["text_list"]     = df["text"].apply(ast.literal_eval)
    df["text_aug_list"] = df["text_augment"].apply(ast.literal_eval)

    def extract_study_id(path: str):
        match = re.search(r'/s(\d+)/', path)
        return match.group(1) if match else None

    expanded_rows = []

    for _, row in df.iterrows():
        study_ids     = [extract_study_id(p) for p in row["image_list"]]
        unique_studies = list(dict.fromkeys(study_ids))   # preserve order

        study_groups: dict = defaultdict(list)
        for path in row["image_list"]:
            sid = extract_study_id(path)
            study_groups[sid].append(path)

        for idx, study_id in enumerate(unique_studies):
            if idx >= len(row["text_list"]):
                continue   # safety guard

            report = row["text_list"][idx]
            if idx < len(row["text_aug_list"]):
                report += " " + row["text_aug_list"][idx]

            expanded_rows.append({
                "subject_id": row["subject_id"],
                "study_id":   study_id,
                "images":     study_groups[study_id],
                "report":     report,
            })

    return pd.DataFrame(expanded_rows)

