class VisionEncoder(nn.Module):
    def __init__(self, freeze: bool = True):
        super().__init__()
       
        self.model = AutoModel.from_pretrained("microsoft/rad-dino")
        if freeze:
            for p in self.model.parameters():
                p.requires_grad = False

    def forward(self, x):
        
        return self.model(pixel_values=x).last_hidden_state  # [B, 257, 768]

    @property
    def num_features(self):
        return self.model.config.hidden_size   # 768


class RadBLIPBioGPT(nn.Module):

    def __init__(
        self,
        biogpt_name: str    = "microsoft/biogpt",
        num_query_tokens: int = 32,
    ):
        super().__init__()

        # ── Vision Encoder ────────────────────────────────────
        self.vision_encoder = VisionEncoder(freeze=True)
        vision_dim = self.vision_encoder.num_features          # 768 (Rad-DINO)

        # ── Q-Former ──────────────────────────────────────────

        # Using BLIP-2 OPT-2.7B: its Q-Former was trained to interface with
        # a decoder-only LLM (OPT), which matches BioGPT's causal LM architecture.
        blip2_model = Blip2ForConditionalGeneration.from_pretrained(
            "Salesforce/blip2-opt-2.7b"
        )
        self.qformer = blip2_model.qformer
        # Reinitialize query tokens with BERT-style init so they start
        # neutral and learn CXR-specific visual summarization from scratch,
        # while the Q-Former transformer weights (pretrained on 129M pairs)
        # are preserved for their learned cross-attention mechanics.
        self.qformer.query_tokens = nn.Parameter(
            torch.zeros(1, num_query_tokens, self.qformer.config.hidden_size)
        )
        nn.init.trunc_normal_(self.qformer.query_tokens, std=0.02)
        self.num_query_tokens = num_query_tokens

        # ── Vision → Q-Former projection ──────────────────────
 
        self.vision_proj = nn.Linear(vision_dim, qformer_vis_dim)

        # ── BioGPT ────────────────────────────────────────────
        self.llm = AutoModelForCausalLM.from_pretrained(biogpt_name)
        for p in self.llm.parameters():
            p.requires_grad = False

        llm_hidden = self.llm.config.hidden_size

        # ── Q-Former → BioGPT projection ──────────────────────
        self.proj = nn.Linear(self.qformer.config.hidden_size, llm_hidden)

    # ──────────────────────────────────────────────────────────
    def forward(
        self,
        images,           # [B, N, 3, 224, 224]
        image_mask,       # [B, N]
        input_ids,
        attention_mask,
        labels,
    ):
        B, N, C, H, W = images.shape

        # ── 1. Encode images ──────────────────────────────────
        image_embeds = self.vision_encoder(images.view(B * N, C, H, W))  # [B*N, 197, 768]
        image_embeds = self.vision_proj(image_embeds)                     # [B*N, 197, 1024]
        T, D = image_embeds.shape[1], image_embeds.shape[2]
        image_embeds = image_embeds.view(B, N, T, D)

        # ── 2. Fuse valid images per study ────────────────────
        fused_tokens = []
        for i in range(B):
            valid = image_embeds[i][image_mask[i].bool()]   # [n_i, T, D]  i.e. [#images, #token, dim_token]
            fused_tokens.append(valid.reshape(-1, D))        # [n_i*T, D]  and the concatenated vector is [image1_tokens || image2_tokens || ...imageN_tokens] i.e. fusion along token dimension

        # ── 3. Pad across batch for Q-Former ──────────────────
        max_tokens = max(t.shape[0] for t in fused_tokens)
        padded_visuals, visual_att_mask = [], []

        for t in fused_tokens:
            pad_len = max_tokens - t.shape[0]
            padded  = torch.cat([
                t,
                torch.zeros(pad_len, D, device=t.device, dtype=t.dtype)
            ], dim=0)
            mask = torch.cat([
                torch.ones(t.shape[0],  device=t.device),
                torch.zeros(pad_len,    device=t.device),
            ])
            padded_visuals.append(padded)
            visual_att_mask.append(mask)

        image_embeds       = torch.stack(padded_visuals)    # [B, max_T, D]
        visual_att_mask    = torch.stack(visual_att_mask)   # [B, max_T]

        # ── 4. Q-Former ───────────────────────────────────────
        query_tokens = self.qformer.query_tokens.expand(B, -1, -1)
        q_out = self.qformer(
            query_embeds=query_tokens,
            encoder_hidden_states=image_embeds,
            encoder_attention_mask=visual_att_mask,
            return_dict=True,
        )
        visual_tokens = self.proj(q_out.last_hidden_state)  # [B, Q, llm_h]

        # ── 5. Prepend visual tokens to text embeddings ───────
        text_embeds    = self.llm.get_input_embeddings()(input_ids)
        inputs_embeds  = torch.cat([visual_tokens, text_embeds], dim=1)

        vis_prefix_mask = torch.ones(
            B, visual_tokens.size(1),
            device=attention_mask.device, dtype=attention_mask.dtype,
        )
        full_attention_mask = torch.cat([vis_prefix_mask, attention_mask], dim=1)

        vis_labels  = torch.full(
            (B, visual_tokens.size(1)), -100,                           # visual labels are masked out
            device=labels.device, dtype=labels.dtype,
        )
        full_labels = torch.cat([vis_labels, labels], dim=1)

        # ── 6. BioGPT forward ────────────────────────────────
        outputs = self.llm(
            inputs_embeds=inputs_embeds,
            attention_mask=full_attention_mask,
            labels=full_labels,
            return_dict=True,
        )
        return outputs.loss

