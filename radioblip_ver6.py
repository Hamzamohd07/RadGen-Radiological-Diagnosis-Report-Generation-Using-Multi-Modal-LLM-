PROMPT = "Chest X-ray Report:\nFindings:\n"

class MIMICCXRDataset(Dataset):

    def __init__(
        self,
        df: pd.DataFrame,
        root_dir: str,
        tokenizer_name: str = "microsoft/biogpt",
        max_length: int = 256,
    ):
        self.df          = df.reset_index(drop=True)
        self.root_dir    = root_dir
        self.max_length  = max_length
        self.tokenizer   = AutoTokenizer.from_pretrained(tokenizer_name)

        
        self.valid_indices = self._filter_valid_indices()
 
        self.processor = AutoImageProcessor.from_pretrained(
            "microsoft/rad-dino"
        )

    def _filter_valid_indices(self):
        """Pre-filter rows whose images actually exist on disk."""
        valid = []
        for i, row in self.df.iterrows():
            all_exist = all(
                os.path.exists(os.path.join(self.root_dir, p))
                for p in row["images"]
            )
            if all_exist:
                valid.append(i)
        print(f"[Dataset] {len(valid)} / {len(self.df)} studies have all images on disk.")
        return valid

    def __len__(self):
        return len(self.valid_indices)

    def __getitem__(self, idx):
        row = self.df.iloc[self.valid_indices[idx]]

        # ── Images ──────────────────────────────────────────
        pil_images = []
        for path in row["images"]:
            full_path = os.path.join(self.root_dir, path)
            pil_images.append(Image.open(full_path).convert("RGB"))

        # processor returns pixel_values: [N, 3, 518, 518]
        images = self.processor(
            images=pil_images,
            return_tensors="pt",
        )["pixel_values"]                      # [N, 3, 518, 518]

        # ── Tokenise ─────────────────────────────────────────
        #   Tokenising PROMPT separately so we can mask it in labels.
        prompt_ids = self.tokenizer(
            PROMPT, add_special_tokens=False
        )["input_ids"]
        prompt_len = len(prompt_ids)

        full_text = PROMPT + row["report"]
        encoding  = self.tokenizer(
            full_text,
            padding="max_length",
            truncation=True,
            max_length=self.max_length,
            return_tensors="pt",
        )

        input_ids      = encoding["input_ids"].squeeze(0)
        attention_mask = encoding["attention_mask"].squeeze(0)

         
        labels = input_ids.clone()
        labels[attention_mask == 0]       = -100   # padding
        labels[:prompt_len]               = -100   # prompt prefix

        return {
            "images":         images,
            "input_ids":      input_ids,
            "attention_mask": attention_mask,
            "labels":         labels,
        }

