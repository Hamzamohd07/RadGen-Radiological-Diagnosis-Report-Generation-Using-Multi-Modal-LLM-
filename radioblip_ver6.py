def freeze_module(module: nn.Module):
    for p in module.parameters():
        p.requires_grad = False

def unfreeze_module(module: nn.Module):
    for p in module.parameters():
        p.requires_grad = True

def unfreeze_last_n_layers_biogpt(model: RadBLIPBioGPT, n_layers: int = 2):
    freeze_module(model.llm)
    total = len(model.llm.biogpt.layers)
    for i in range(total - n_layers, total):
        for p in model.llm.biogpt.layers[i].parameters():
            p.requires_grad = True
    print(f"[Unfreeze] Last {n_layers} / {total} BioGPT layers are now trainable.")

